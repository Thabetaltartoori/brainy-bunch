const I18nContext = createContext(null);
const STORAGE_KEY = 'bb.lang';

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ar' || saved === 'en') return saved;
    return navigator.language?.startsWith('ar') ? 'ar' : 'en';
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    localStorage.setItem(STORAGE_KEY, lang);
  }, [lang]);

  const setLang = useCallback((next) => setLangState(next), []);
  const toggleLang = useCallback(
    () => setLangState((l) => (l === 'ar' ? 'en' : 'ar')),
    [],
  );

  const value = useMemo(() => {
    const dict = STRINGS[lang] ?? STRINGS.en;
    /** t('key') — falls back to English, then to the key itself. */
    const t = (key) => dict[key] ?? STRINGS.en[key] ?? key;
    return { lang, dir: lang === 'ar' ? 'rtl' : 'ltr', t, setLang, toggleLang };
  }, [lang, setLang, toggleLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside <I18nProvider>');
  return ctx;
}
